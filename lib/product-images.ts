// Product photography is uploaded to Supabase Storage instead of being linked
// from an external host, so the shop owns the files.
//
// Imported by the admin editor (a client component) and by the catalogue readers
// (server), so this module must stay free of "server-only", secrets and any
// Supabase client of its own.

/** The storage bucket that holds every product photo. Mirrors migration 0009. */
export const PRODUCT_IMAGE_BUCKET = "product-images";

/** Uploads larger than this are rejected before they start. Mirrors the bucket's own limit. */
export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;

/** The only formats the bucket accepts. */
export const IMAGE_MIME_TYPES = ["image/jpeg", "image/png", "image/webp", "image/avif"];

/** One gallery row, with its public URL already resolved. */
export type ProductImage = {
    id: string;
    /** Object key inside the bucket. */
    path: string;
    /** Public URL, safe to hand straight to next/image. */
    url: string;
    alt: string | null;
    sort_order: number;
};

/**
 * What the gallery actions report back. They return instead of redirecting so the
 * editor can show a failure inline without losing the page.
 */
export type ImageResult = { ok: true } | { ok: false; message: string };

/**
 * Public URL for an object in the bucket. Keys are generated by us from a slug
 * and a UUID, so they never need escaping.
 */
export function productImageUrl(path: string): string {
    const base = (process.env.NEXT_PUBLIC_SUPABASE_URL ?? "").replace(/\/+$/, "");
    return `${base}/storage/v1/object/public/${PRODUCT_IMAGE_BUCKET}/${path}`;
}

/** Gallery rows in display order, resolved to public URLs. */
export function imageUrls(rows: { path: string; sort_order: number }[] | null): string[] {
    return [...(rows ?? [])]
        .sort((a, b) => a.sort_order - b.sort_order)
        .map((im) => productImageUrl(im.path));
}

/** Guards the product id the slug rule allows, so a key is never built from junk. */
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/**
 * Object key for a new upload: one folder per product, one unique name per file.
 * An unusable prefix falls back to a shared folder rather than failing the upload.
 */
export function productImagePath(prefix: string, mime: string): string {
    const folder = SLUG.test(prefix) ? prefix : "unsorted";
    const ext = mime === "image/png" ? "png" : mime === "image/webp" ? "webp" : mime === "image/avif" ? "avif" : "jpg";
    return `${folder}/${crypto.randomUUID()}.${ext}`;
}

/** Error message for a file we refuse to upload, or null when it is fine. */
export function imageFileError(file: File): string | null {
    if (!IMAGE_MIME_TYPES.includes(file.type)) {
        return `${file.name} is not a JPG, PNG, WebP or AVIF image.`;
    }
    if (file.size > MAX_IMAGE_BYTES) {
        return `${file.name} is over ${MAX_IMAGE_BYTES / 1024 / 1024} MB. Please shrink it and try again.`;
    }
    return null;
}
